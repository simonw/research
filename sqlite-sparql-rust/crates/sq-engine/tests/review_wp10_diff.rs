//! Adversarial review (WP10): hand-written differential cases in the fuzzer's blind spots
//! (empty registered named graphs, query-level VALUES, single-row GROUP_CONCAT / SAMPLE,
//! EXISTS + BIND substitution shapes), compared with sq-oracle under every configuration.
#[allow(dead_code, unused_imports)]
mod fuzz;

use sq_core::plan::JoinPolicy;
use sq_core::store::{QuadStore, QuadStoreWriter};

use fuzz::compare::{same, Free, Outcome};
use fuzz::data::Dataset;
use fuzz::engines::{native, oracle, oracle_options, options, Config, StoreKind, Stores};
use fuzz::query::Order;

const POLICIES: [JoinPolicy; 5] =
    [JoinPolicy::Auto, JoinPolicy::PreferHash, JoinPolicy::PreferBind, JoinPolicy::PreferMerge, JoinPolicy::NoSql];

/// Registers `<http://ex/{name}>` as an empty named graph in every store.
fn create_graph(stores: &Stores, name: &str) {
    let iri = format!("http://ex/{name}");
    let iri = oxrdf::NamedNodeRef::new_unchecked(&iri);
    let id = stores.mem.intern(iri.into()).unwrap();
    stores.mem.create_graph(id).unwrap();
    for db in [&stores.sqlite, &stores.file] {
        let scope = db.store.write_scope(0).unwrap();
        let id = db.store.intern(iri.into()).unwrap();
        db.store.create_graph(id).unwrap();
        scope.commit().unwrap();
    }
}

/// Every mismatch of `query` (native vs oracle, per configuration, and oracle across stores).
fn mismatches(stores: &Stores, query: &str, order: Order) -> Vec<String> {
    let text = format!("{}{query}", fuzz::query::PREFIXES);
    let parsed = sq_plan::parse_query(&text, None).expect("query parses");
    let oopts = oracle_options(false);
    let mut out = Vec::new();
    let truth_mem = stores.with(StoreKind::Mem, |s| oracle(&*s, &parsed, &oopts));
    for kind in StoreKind::ALL {
        let truth = stores.with(kind, |s| oracle(&*s, &parsed, &oopts));
        if let Err(d) = same(&truth_mem, &truth, order, Free::All) {
            out.push(format!("oracle {kind:?} vs Mem: {d}"));
        }
        for cfg in Config::all(&POLICIES).into_iter().filter(|c| c.store == kind) {
            let got = stores.with(kind, |s| native(s, &parsed, &options(&cfg, false, true)));
            if let Err(d) = same(&truth, &got, order, Free::Minted) {
                out.push(format!("{cfg:?}: {d}\n  oracle: {}  native: {}", truth.describe(order, 10), got.describe(order, 10)));
            }
        }
    }
    if let Outcome::Error(e) = &truth_mem {
        out.push(format!("oracle error: {e}"));
    }
    out
}

fn stores(trig: &str) -> Stores {
    let data = Dataset::from_trig(trig, false);
    Stores::load(&data)
}

const DATA: &str = "\
:s0 :p0 :s1 .
:s1 :p0 :s2 .
:s1 :p1 \"a\" .
:s2 :p1 1 .
:g0 { :s1 :p0 :s2 }
:g0 { :s2 :p2 :s0 }
:g1 { :s0 :p1 \"b\" }
";

#[test]
fn review_empty_registered_graphs_agree_with_the_oracle() {
    let st = stores(DATA);
    create_graph(&st, "s9");
    let queries = [
        "SELECT ?g WHERE { GRAPH ?g { } }",
        "SELECT ?g ?s WHERE { GRAPH ?g { OPTIONAL { ?s :p0 ?o } } }",
        "SELECT * WHERE { GRAPH ?g { BIND(1 AS ?x) } }",
        "SELECT * WHERE { GRAPH :s9 { } }",
        "ASK { GRAPH :s9 { } }",
        "SELECT ?g (COUNT(*) AS ?c) WHERE { GRAPH ?g { OPTIONAL { ?s ?p ?o } } } GROUP BY ?g",
        "SELECT * FROM NAMED :s9 WHERE { GRAPH ?g { } }",
        "SELECT ?g WHERE { GRAPH ?g { FILTER NOT EXISTS { ?s ?p ?o } } }",
        "SELECT ?g ?x WHERE { GRAPH ?g { VALUES ?x { 1 2 } } }",
        "SELECT ?g WHERE { ?s :p0 ?o GRAPH ?g { MINUS { ?s :p0 ?o } } }",
    ];
    let bad: Vec<String> = queries.iter().flat_map(|q| mismatches(&st, q, Order::Bag).into_iter().map(move |m| format!("{q}\n  {m}"))).collect();
    assert!(bad.is_empty(), "{}", bad.join("\n"));
}

#[test]
fn review_blind_spot_shapes_agree_with_the_oracle() {
    let st = stores(DATA);
    let queries = [
        // Query-level VALUES (never generated by the fuzzer).
        "SELECT * WHERE { ?s :p0 ?o } VALUES ?o { :s1 UNDEF }",
        "SELECT * WHERE { ?s :p0 ?o OPTIONAL { ?o :p1 ?v } } VALUES (?s ?v) { (:s0 UNDEF) (UNDEF \"a\") }",
        // Single-element groups make GROUP_CONCAT and SAMPLE deterministic.
        "SELECT ?s (GROUP_CONCAT(?o) AS ?c) (SAMPLE(?o) AS ?x) WHERE { ?s :p1 ?o } GROUP BY ?s",
        "SELECT (GROUP_CONCAT(DISTINCT ?o ; SEPARATOR=\"|\") AS ?c) WHERE { :s1 :p1 ?o }",
        // EXISTS substitution of BIND / VALUES / sub-select targets.
        "SELECT * WHERE { ?a :p0 ?b FILTER EXISTS { ?b :p0 ?c BIND(?c AS ?a) } }",
        "SELECT * WHERE { ?a :p0 ?b FILTER NOT EXISTS { BIND(:s1 AS ?a) } }",
        "SELECT * WHERE { ?a :p0 ?b FILTER EXISTS { VALUES ?a { :s0 } } }",
        "SELECT * WHERE { ?a :p0 ?b FILTER EXISTS { { SELECT ?a WHERE { ?a :p1 ?z } } } }",
        "SELECT * WHERE { ?a :p0 ?b FILTER EXISTS { ?b :p1 ?v BIND(STR(?v) AS ?a) } }",
        "SELECT * WHERE { ?a :p0 ?b FILTER EXISTS { OPTIONAL { ?b :p0 ?c } BIND(COALESCE(?c, ?b) AS ?a) } }",
        // MINUS where the right side only shares a variable through a BIND.
        "SELECT * WHERE { ?a :p0 ?b MINUS { ?x :p0 ?y BIND(?x AS ?a) } }",
        // Paths: zero-length with both ends constant / unbound subject in GRAPH.
        "SELECT * WHERE { :s9 :p0* :s9 }",
        "SELECT * WHERE { GRAPH ?g { ?x :p0* ?x } }",
        "SELECT * WHERE { ?x (:p0|^:p0)* :s0 FILTER(?x != :s0) }",
    ];
    let bad: Vec<String> = queries.iter().flat_map(|q| mismatches(&st, q, Order::Bag).into_iter().map(move |m| format!("{q}\n  {m}"))).collect();
    assert!(bad.is_empty(), "{}", bad.join("\n"));
}

#[test]
fn review_bnode_in_join_mints_one_node_per_solution() {
    // BNODE() on the probe side of a BindJoin used to be re-evaluated per seed; sq-exec now
    // hash-joins against one evaluation of a right side that mints values.
    let st = stores(":s3 :p0 :s0 .\n_:x0 :p0 :s0 .");
    let bad = mismatches(&st, "SELECT * WHERE { { BIND(BNODE() AS ?e) } UNION { VALUES ?f { \"x\"^^:dt } } ?f :p0 :s0 }", Order::Bag);
    assert!(bad.is_empty(), "{}", bad.join("\n"));
}

#[test]
fn review_store_views_are_consistent() {
    // Sanity: the empty graph shows up in every store's registry.
    let st = stores(DATA);
    create_graph(&st, "s9");
    let n = |s: &dyn QuadStore| s.named_graphs().unwrap().len();
    assert_eq!(n(&st.mem), 3);
    assert_eq!(st.with(StoreKind::Sqlite, |s| n(&*s)), 3);
    assert_eq!(st.with(StoreKind::File, |s| n(&*s)), 3);
}

#[test]
fn review_exists_bind_substitution_shapes_agree_with_the_oracle() {
    let st = stores(DATA);
    let queries = [
        "SELECT * WHERE { ?a :p0 ?b FILTER EXISTS { ?b :p0 ?c BIND(?c AS ?a) ?x :p0 ?a } }",
        "SELECT * WHERE { ?a :p0 ?b FILTER EXISTS { ?b ?q ?c BIND(?c AS ?a) ?a ?r ?w } }",
        "SELECT * WHERE { ?a :p0 ?b FILTER EXISTS { ?b :p1 ?c BIND(:s0 AS ?a) { ?y :p0 ?a } } }",
        "SELECT * WHERE { ?a ?p ?b FILTER EXISTS { ?b ?q ?c BIND(?c AS ?a) OPTIONAL { ?a :p0 ?w } } }",
        "SELECT * WHERE { ?a ?p ?b FILTER NOT EXISTS { ?b ?q ?c BIND(?c AS ?a) ?a ?r ?w } }",
        "SELECT * WHERE { ?a :p0 ?b FILTER EXISTS { { ?b :p0 ?c BIND(?c AS ?a) } UNION { BIND(:s9 AS ?a) } ?a ?pp ?oo } }",
        "SELECT * WHERE { GRAPH ?g { ?s ?p ?o } FILTER EXISTS { BIND(:g1 AS ?g) ?s ?p ?o } }",
        "SELECT * WHERE { GRAPH ?g { ?s ?p ?o } FILTER EXISTS { ?s ?p ?o BIND(:g1 AS ?g) GRAPH ?g { ?s ?p ?o } } }",
        "SELECT * WHERE { ?a :p0 ?b FILTER EXISTS { ?b :p0 ?c { SELECT (:s1 AS ?a) WHERE {} } ?a :p0 ?c } }",
        "SELECT * WHERE { ?a :p0 ?b FILTER EXISTS { ?b :p0 ?c VALUES ?a { :s1 :s0 } ?a :p0 ?b } }",
        "SELECT * WHERE { ?a :p0 ?b FILTER EXISTS { ?b :p0* ?c BIND(?c AS ?a) ?a :p0* ?d } }",
        "SELECT * WHERE { ?a :p0 ?b OPTIONAL { ?b :p0 ?c FILTER EXISTS { ?c ?q ?v BIND(?v AS ?a) ?a ?r ?w } } }",
        "SELECT * WHERE { ?a :p0 ?b MINUS { ?b :p0 ?c BIND(?c AS ?a) ?a ?r ?w } }",
    ];
    let bad: Vec<String> = queries.iter().flat_map(|q| mismatches(&st, q, Order::Bag).into_iter().map(move |m| format!("{q}\n  {m}"))).collect();
    assert!(bad.is_empty(), "{}", bad.join("\n"));
}

/// The differential fuzzer fills its SQLite stores through the generic loader
/// (`sq_engine::load`, one `intern` per term); production databases are filled by sq-sqlite's
/// bulk loader (§2.3). Every literal of the fuzzer vocabulary, loaded both ways, must give
/// the same answers.
#[test]
fn review_bulk_loaded_store_agrees_with_the_generic_loader() {
    use fuzz::data::LITERALS;
    let mut trig = String::from("@prefix : <http://ex/> .\n@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .\n");
    for (i, l) in LITERALS.iter().enumerate() {
        trig.push_str(&format!(":s{} :p{} {l} .\n:g0 {{ :s{} :p3 {l} }}\n_:b{} :p2 {l} .\n", i % 12, i % 4, i % 12, i % 3));
    }
    let mem = sq_memstore::MemStore::new();
    sq_engine::load(&mem, trig.as_bytes(), oxrdfio::RdfFormat::TriG, None, None).unwrap();
    let conn = rusqlite::Connection::open_in_memory().unwrap();
    // SAFETY: `conn` outlives `store` (dropped at the end of the test, after the store).
    let db = unsafe { sq_sqlite::RawDb::from_ptr(conn.handle()) };
    let shared = sq_sqlite::StorageShared::new(db, sq_sqlite::StorageConfig::default());
    shared.arm_pool();
    let store = sq_sqlite::SqliteStore::new(shared);
    store.ensure_schema().unwrap();
    let scope = store.write_scope(0).unwrap();
    store.bulk_load(sq_sqlite::LoadSource::Bytes(trig.as_bytes()), &sq_sqlite::LoadOptions::new(oxrdfio::RdfFormat::TriG)).unwrap();
    scope.commit().unwrap();

    let mut queries = vec![
        "SELECT * WHERE { ?s ?p ?o }".to_owned(),
        "SELECT * WHERE { GRAPH ?g { ?s ?p ?o } }".to_owned(),
        "SELECT ?o (COUNT(*) AS ?n) WHERE { ?s ?p ?o } GROUP BY ?o".to_owned(),
        "SELECT ?a ?b WHERE { ?x :p3 ?a . ?y :p2 ?b FILTER(sameTerm(?a, ?b)) }".to_owned(),
        "SELECT ?a ?b WHERE { ?x :p3 ?a . ?y :p2 ?b FILTER(?a = ?b) }".to_owned(),
        "SELECT ?a WHERE { ?x :p3 ?a . ?y :p2 ?a }".to_owned(),
    ];
    for l in LITERALS {
        queries.push(format!("SELECT ?s ?p WHERE {{ ?s ?p {l} }}"));
        queries.push(format!("SELECT ?o WHERE {{ ?s :p3 ?o FILTER(?o = {l}) }}"));
    }
    let oopts = oracle_options(false);
    let mut bad = Vec::new();
    for q in &queries {
        let text = format!("{}{q}", fuzz::query::PREFIXES);
        let parsed = sq_plan::parse_query(&text, None).unwrap();
        let truth = oracle(&mem, &parsed, &oopts);
        let read = store.read_scope(0).unwrap();
        let st: std::rc::Rc<dyn QuadStore> = std::rc::Rc::new(store.clone());
        let got_oracle = oracle(&*st, &parsed, &oopts);
        let cfg = Config { store: StoreKind::Sqlite, policy: JoinPolicy::Auto, reorder: true };
        let got = native(st, &parsed, &options(&cfg, false, true));
        read.close().unwrap();
        for (what, o) in [("oracle", &got_oracle), ("native", &got)] {
            if let Err(d) = same(&truth, o, Order::Bag, Free::All) {
                bad.push(format!("{q}: bulk-loaded {what}: {d}"));
            }
        }
    }
    store.shared().disarm_and_finalize();
    drop(store);
    drop(conn);
    assert!(bad.is_empty(), "{}", bad.join("\n"));
}

/// The fuzzer never binds `?g` to an actual graph name outside `GRAPH ?g` (its VALUES rows
/// and expression constants for `?g` are subject IRIs or literals), so seeded / filtered
/// graph variables and the GRAPH ?g push rule's "no expression mentions ?g" condition are
/// only reached here.
#[test]
fn review_graph_variable_bound_to_real_graph_names_agrees_with_the_oracle() {
    let data = format!("{DATA}:g0 :p0 :g1 .\n:g1 {{ :g1 :p1 :s0 }}\n:g1 {{ :s1 :p0 :s2 }}\n");
    let st = stores(&data);
    create_graph(&st, "s9");
    let queries = [
        "SELECT * WHERE { VALUES ?g { :g0 :g1 :gx :s9 } GRAPH ?g { ?s ?p ?o } }",
        "SELECT * WHERE { GRAPH ?g { ?s ?p ?o } VALUES ?g { :g1 } }",
        "SELECT * WHERE { BIND(:g0 AS ?g) GRAPH ?g { ?s ?p ?o } }",
        "SELECT * WHERE { GRAPH ?g { ?s ?p ?o FILTER(?g = :g0) } }",
        "SELECT * WHERE { GRAPH ?g { ?s ?p ?o } FILTER(?g != :g0) }",
        "SELECT * WHERE { GRAPH ?g { ?s ?p ?o BIND(?g AS ?h) } }",
        "SELECT * WHERE { ?s :p0 ?o GRAPH ?g { OPTIONAL { ?x ?q ?g } } }",
        "SELECT * WHERE { GRAPH ?g { ?g ?p ?o } }",
        "SELECT * WHERE { ?g :p0 ?h GRAPH ?h { ?h ?p ?o } }",
        "SELECT * WHERE { GRAPH ?g { ?s ?p ?o MINUS { ?s ?p ?o FILTER(?g = :g0) } } }",
        "SELECT * WHERE { GRAPH ?g { ?s ?p ?o FILTER EXISTS { GRAPH :g1 { ?s ?p ?o } } } }",
        "SELECT * WHERE { GRAPH ?g { ?s ?p ?o FILTER NOT EXISTS { GRAPH ?g { ?o ?q ?r } } } }",
        "SELECT * WHERE { GRAPH ?g { { SELECT ?s WHERE { ?s ?p ?o } } } }",
        "SELECT * WHERE { VALUES ?g { :g0 :g1 } GRAPH ?g { ?s :p0* ?o } }",
        "SELECT * FROM NAMED :g0 WHERE { VALUES ?g { :g0 :g1 } GRAPH ?g { ?s ?p ?o } }",
        "SELECT * WHERE { GRAPH ?g { ?s ?p ?o } GRAPH ?h { ?o ?q ?r } FILTER(?g != ?h) }",
        "SELECT ?g (COUNT(*) AS ?n) WHERE { VALUES ?g { :g0 :g1 :s9 } OPTIONAL { GRAPH ?g { ?s ?p ?o } } } GROUP BY ?g",
        "SELECT * WHERE { ?a :p0 ?g OPTIONAL { GRAPH ?g { ?x ?y ?z } } }",
        "ASK { GRAPH ?g { ?s ?p ?o FILTER(STR(?g) = \"http://ex/g1\") } }",
    ];
    let bad: Vec<String> = queries.iter().flat_map(|q| mismatches(&st, q, Order::Bag).into_iter().map(move |m| format!("{q}\n  {m}"))).collect();
    assert!(bad.is_empty(), "{}", bad.join("\n"));
}
